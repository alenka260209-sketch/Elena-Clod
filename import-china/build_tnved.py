def build_sheet(ws, src_rows, first, last, item_map, cols, freight_cell, docs_cost_expr, title, subtitle, qty_is_input):
    """cols: dict of role -> column index"""
    c = cols
    ws["A1"] = title
    ws["A1"].font = f_title
    ws["A2"] = subtitle
    ws["A2"].font = f_note
    ws["A3"] = ("Жёлтые ячейки — вводные (вес, цена, кол-во). Зелёным выделен код ТН ВЭД, розовым — низкая уверенность "
                "(нужна консультация брокера или предварительное решение ФТС). Ставки пошлин — по справочникам ЕТТ ЕАЭС, сверить на дату ввоза.")
    ws["A3"].font = f_note
    ws["A3"].alignment = Alignment(wrap_text=True)
    ws.merge_cells(start_row=3, start_column=1, end_row=3, end_column=12)
    ws.row_dimensions[3].height = 28

    # headers
    for col_idx, name in cols["_headers"]:
        cell = ws.cell(5, col_idx, name)
        cell.font = f_bold
        cell.fill = fill_head
        cell.border = border
        cell.alignment = center
    ws.row_dimensions[5].height = 45

    L = get_column_letter
    fr, lr = first, last
    inv_rng = f"${L(c['inv'])}${fr}:${L(c['inv'])}${lr}"

    sum_start = lr + 3
    R_TS = sum_start + 2
    R_FEE = sum_start + 5
    R_BROKER = sum_start + 7
    R_DOCS = sum_start + 8
    overhead = f"(${L(4)}${R_FEE}+${L(4)}${R_BROKER}+${L(4)}${R_DOCS})"
    ts_total = f"${L(4)}${R_TS}"

    for r_src, vals, is_section in src_rows:
        r = r_src + 1
        if is_section:
            ws.cell(r, 1, vals[0])
            style_range(ws, r, 1, c["last"], font=f_bold, fill=fill_sec)
            continue
        for i, v in enumerate(vals):
            ws.cell(r, i + 1, v)
        style_range(ws, r, 1, c["last"])
        code, docs, conf, note, *rest = item_map[r_src]
        desc, pct, eurkg, rate_status = CODES[code]
        qcol = L(c["qty"])
        ws.cell(r, c["code"], code).fill = fill_code
        ws.cell(r, c["code"]).font = f_bold
        ws.cell(r, c["desc"], desc)
        ws.cell(r, c["pct"], pct if pct is not None else None).number_format = PCT
        ws.cell(r, c["eurkg"], eurkg).number_format = '0.00;;"-"'
        for key in ("w", "price"):
            cell = ws.cell(r, c[key])
            cell.fill = fill_input
            cell.font = f_input
            cell.number_format = USD if key == "price" else '0.000'
        if qty_is_input:
            qc = ws.cell(r, c["qty"], rest[0] if rest else None)
            qc.fill = fill_input
            qc.font = f_input
        pc, wc, ic, ec = L(c["price"]), L(c["w"]), L(c["inv"]), L(c["eurkg"])
        ws.cell(r, c["inv"], f'=IF(AND(ISNUMBER({qcol}{r}),ISNUMBER({pc}{r})),{qcol}{r}*{pc}{r},0)').number_format = USD
        ws.cell(r, c["frt"], f'=IF(SUM({inv_rng})=0,0,{ic}{r}/SUM({inv_rng})*{freight_cell})').number_format = USD
        ws.cell(r, c["ts"], f'=({ic}{r}+{L(c["frt"])}{r})*Параметры!$B$4').number_format = RUB
        tsc = L(c["ts"])
        ws.cell(r, c["duty"], f'=MAX({tsc}{r}*N({L(c["pct"])}{r}),IF(AND(ISNUMBER({wc}{r}),ISNUMBER({qcol}{r})),{qcol}{r}*{wc}{r}*N({ec}{r})*Параметры!$B$5,0))').number_format = RUB
        dc = L(c["duty"])
        ws.cell(r, c["vat"], f'=({tsc}{r}+{dc}{r})*Параметры!$B$6').number_format = RUB
        ws.cell(r, c["tot"], f'={dc}{r}+{L(c["vat"])}{r}').number_format = RUB
        ws.cell(r, c["unit"], f'=IF(OR(N({qcol}{r})=0,{tsc}{r}=0),"",({tsc}{r}+{dc}{r}+{overhead}*{tsc}{r}/{ts_total})/{qcol}{r})').number_format = RUB
        ws.cell(r, c["docs"], docs)
        ws.cell(r, c["conf"], conf).alignment = center
        full_note = note
        if rate_status != "по справочникам" and not rate_status.startswith("по справочникам ("):
            full_note = (f"Ставка пошлины: {rate_status}. " + note).strip()
        if eurkg:
            full_note = ("Специфическая/комбинированная ставка — для расчёта обязательно укажите вес нетто. " + full_note).strip()
        ws.cell(r, c["note"], full_note)
        if conf == "низкая":
            ws.cell(r, c["conf"]).fill = fill_low
        ws.cell(r, c["code"]).comment = Comment(f"{fmt_code(code)}\n{desc}\nСтавка: {rate_status}", "Claude")

    # ---- итоги
    S = sum_start
    ws.cell(S, 2, "ИТОГО ПО ПАРТИИ (одна декларация на товары)").font = f_bold
    col_code = L(c["code"])
    code_rng = f"{col_code}{fr}:{col_code}{lr}"
    rows = [
        (S + 1, "Стоимость по инвойсу, USD", f"=SUM({L(c['inv'])}{fr}:{L(c['inv'])}{lr})", USD),
        (S + 2, "Таможенная стоимость, ₽", f"=SUM({L(c['ts'])}{fr}:{L(c['ts'])}{lr})", RUB),
        (S + 3, "Ввозная пошлина, ₽", f"=SUM({L(c['duty'])}{fr}:{L(c['duty'])}{lr})", RUB),
        (S + 4, "НДС 22% при ввозе, ₽", f"=SUM({L(c['vat'])}{fr}:{L(c['vat'])}{lr})", RUB),
        (S + 5, "Таможенный сбор, ₽", f"=IF(D{S+2}=0,0,LOOKUP(D{S+2},{FEE_LO},{FEE_V}))", RUB),
        (S + 6, "ИТОГО платежей на таможне, ₽", f"=D{S+3}+D{S+4}+D{S+5}", RUB),
        (S + 7, "Брокер (ДТ + доп. коды), ₽", f"=Параметры!$B$12+MAX(0,D{S+10}-Параметры!$B$14)*Параметры!$B$13", RUB),
        (S + 8, "Разрешительные документы (оценка), ₽", docs_cost_expr, RUB),
        (S + 9, "ВСЕГО расходов на растаможку, ₽", f"=D{S+6}+D{S+7}+D{S+8}", RUB),
        (S + 10, "Разных кодов ТН ВЭД в партии", len({item_map[k][0] for k in item_map}), "0"),
        (S + 11, "в т. ч. НДС к вычету (при ОСНО), ₽", f"=D{S+4}", RUB),
        (S + 12, "Себестоимость партии на складе без НДС (без доставки по РФ), ₽", f"=D{S+2}+D{S+3}+D{S+5}+D{S+7}+D{S+8}", RUB),
    ]
    for r, label, fml, fmt in rows:
        ws.cell(r, 2, label).font = f_bold if "ИТОГО" in label or "ВСЕГО" in label else f_norm
        cell = ws.cell(r, 4, fml)
        cell.number_format = fmt
        cell.font = f_bold if "ИТОГО" in label or "ВСЕГО" in label else f_norm
        cell.border = border
        ws.merge_cells(start_row=r, start_column=2, end_row=r, end_column=3)
        if r == S + 10:
            cell.font = f_input
            cell.fill = fill_input
            cell.comment = Comment("Число разных кодов в таблице на момент составления. Если меняете коды — обновите вручную.", "Claude")
    ws.freeze_panes = ws.cell(6, 3)
    return S


