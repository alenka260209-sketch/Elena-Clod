OK = PatternFill("solid", fgColor="D4EDDA")
NUM = '#,##0.00;[Red]-#,##0.00;"–"'

wb = Workbook()


def sheet(title, header_lines, columns, widths):
    ws = wb.create_sheet(title)
    r = 1
    for i, line in enumerate(header_lines):
        ws.cell(r, 1, line).font = Font(bold=(i == 0), size=13 if i == 0 else 10)
        r += 1
    r += 1
    for c, name in enumerate(columns, 1):
        cell = ws.cell(r, c, name)
        cell.font = Font(bold=True)
        cell.fill = HEAD
        cell.border = BORDER
        cell.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
    ws.row_dimensions[r].height = 60
    for c, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(c)].width = w
    ws.freeze_panes = ws.cell(r + 1, 2)
    return ws, r + 1


def put(ws, r, values, fill=None, bold=False):
    for c, v in enumerate(values, 1):
        cell = ws.cell(r, c, v)
        cell.border = BORDER
        if isinstance(v, (int, float)) or (isinstance(v, str) and v.startswith("=")):
            cell.number_format = NUM
        else:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
        if fill:
            cell.fill = fill
        if bold:
            cell.font = Font(bold=True)


def mark(ws, r, cols):
    """Подсветка ячеек отклонений: красным если не ноль, зелёным если ноль."""
    for c in cols:
        L = get_column_letter(c)
        ws.conditional_formatting.add(
            f"{L}{r}", __import__("openpyxl").formatting.rule.CellIsRule(
                operator="notBetween", formula=["-0.005", "0.005"], fill=BAD))
        ws.conditional_formatting.add(
            f"{L}{r}", __import__("openpyxl").formatting.rule.CellIsRule(
                operator="between", formula=["-0.005", "0.005"], fill=OK))


